import path from 'node:path';
import { createFeatureBranch } from '../core/pullRequests/branches.js';
/**
 * Automated Pull Request Generation Engine
 *
 * Authenticates via `@octokit/app` installation tokens, requires explicit opt-in
 * to replace an existing license, creates an isolated feature branch, commits
 * the generated LICENSE file, and opens an explanatory pull request.
 */

import { repositoryService } from '../core/repository/service.js';
import { commitFiles } from '../core/pullRequests/files.js';
import { inspectRootEntries } from '../../public/js/analyzer.js';
import { ServiceError, validatePrRequest } from './licenseService.js';
import { authorizeRepositoryRead } from '../core/github/authorize.js';
import {
  README_PLACEMENTS,
  generateUnifiedDiff,
  smartUpdateReadme,
  inspectReadme
} from '../../public/js/readme.js';
import { prepareReadmeUpdate, fetchRepositoryReadme } from './readmeService.js';

export { formatLicenseBranchName, buildPullRequestBody };

/**
 * Format a deterministic feature branch name for adding a specific SPDX license.
 *
 * @param {string} licenseId
 * @param {boolean} [replaceExisting=false]
 * @returns {string}
 */
function formatLicenseBranchName(licenseId, replaceExisting = false) {
  const slug = String(licenseId)
    .toLowerCase()
    .replace(/[^a-z0-9.-]+/g, '-')
    .replace(/^-+|-+$/g, '');
  return `chore/${replaceExisting ? 'replace' : 'add'}-license-${slug}`;
}

/**
 * Build a clear, plain-language Pull Request description summarizing rights and obligations.
 *
 * @param {object} params
 * @returns {string}
 */
function buildPullRequestBody({ explanation, licensePackage, defaultBranch, existingLicensePath, readmeUpdate, readmePlacement }) {
  const formatBullets = (items, emptyFallback) => {
    if (!items || items.length === 0) return `- ${emptyFallback}`;
    return items.map((item) => `- **${item.label}:** ${item.description}`).join('\n');
  };

  const lines = [
    '## Summary',
    existingLicensePath
      ? `This automated pull request replaces the existing license in \`${existingLicensePath}\` with **${explanation.name} (\`${explanation.id}\`)** targeting \`${defaultBranch}\`. Review the license diff before merging.`
      : `This automated pull request adds a \`${licensePackage.filename}\` file under **${explanation.name} (\`${explanation.id}\`)** targeting \`${defaultBranch}\`.`,
    '',
    explanation.plainSummary,
    '',
    '### Key Policy Highlights',
    `- **Copyleft Obligation:** ${explanation.policyHighlights.copyleftObligation}`,
    `- **Patent Clause:** ${explanation.policyHighlights.patentClause}`,
    `- **Network-Use Trigger:** ${explanation.policyHighlights.networkUseTrigger}`,
    `- **Distribution Rules:** ${explanation.policyHighlights.distributionRequirements}`,
    '',
    '### Permissions',
    formatBullets(explanation.canDo, 'Standard copyright restrictions apply.'),
    '',
    '### Conditions',
    formatBullets(explanation.mustDo, 'No additional conditions.'),
    '',
    '### Limitations',
    formatBullets(explanation.cannotDo, 'No explicit limitations listed.'),
    '',
    '### Reference',
    `- SPDX Specification: ${explanation.sourceUrls.spdx}`,
    `- Official License Text: ${explanation.sourceUrls.official}`,
    '',
    '> *Generated by Open Workers. This summary is informational and does not constitute formal legal advice.*'
  ];

  if (readmeUpdate) {
    lines.splice(
      3,
      0,
      `README: ${readmeUpdate.changed ? 'Updates' : 'Already includes the selected mention in'} \`${readmeUpdate.path}\` (${readmePlacement}).`,
      ...(readmeUpdate.reviewExisting
        ? ['Existing README license wording or badges were preserved. Review them for consistency with the selected license.']
        : []),
      ''
    );
  }
  return lines.join('\n');
}

async function detectExistingLicenseOnBranch(octokit, { owner, repo, defaultBranch }) {
  const [contentsResult, licenseResult] = await Promise.all([
    octokit.rest.repos.getContent({ owner, repo, path: '', ref: defaultBranch }).catch((err) => {
      if (err?.status === 404) return { data: [] };
      throw err;
    }),
    octokit.rest.licenses.getForRepo({ owner, repo, ref: defaultBranch }).catch((err) => {
      if (err?.status === 404) return null;
      throw err;
    })
  ]);

  const entries = Array.isArray(contentsResult?.data) ? contentsResult.data : [];
  const rootObservations = inspectRootEntries(entries);

  return [
    ...new Set([
      ...rootObservations.licenseFiles.map((file) => file.path),
      ...(licenseResult?.data?.path ? [licenseResult.data.path] : [])
    ])
  ];
}

/**
 * Preview the exact changes (files, diff, conflicts, warnings) that would be committed in a License PR.
 *
 * @param {object} params
 * @returns {Promise<object>}
 */
export async function previewLicensePullRequest({
  repo: repoInput,
  licenseId,
  year,
  holder,
  replaceExisting = false,
  readmePlacement = 'both',
  badgeAction,
  sectionAction,
  customReadmeContent,
  githubContext,
  authorization,
  sessionToken,
  createUserClient
}) {
  if (readmePlacement && !README_PLACEMENTS.includes(readmePlacement)) {
    throw new ServiceError(400, 'readmePlacement must be none, top, bottom, or both.', 'INVALID_INPUT');
  }
  const validated = validatePrRequest({ repo: repoInput, licenseId, year, holder });
  const { owner, repo, fullName, explanation, licensePackage } = validated;

  let octokit = null;
  let installed = false;

  if (githubContext?.isAppConfigured && typeof githubContext.resolveRepoInstallation === 'function') {
    try {
      const resolution = await githubContext.resolveRepoInstallation(owner, repo);
      if (resolution?.installed && resolution.octokit) {
        octokit = resolution.octokit;
        installed = true;
      }
    } catch {
      // Fall through to public octokit
    }
  }

  if (!octokit) {
    octokit = githubContext?.createPublicOctokit ? githubContext.createPublicOctokit() : null;
  }
  if (!octokit) {
    throw new ServiceError(503, 'GitHub client could not be initialized.', 'SERVICE_UNAVAILABLE');
  }

  let repoData;
  try {
    repoData = await octokit.rest.repos.get({ owner, repo }).then((r) => r.data);
  } catch (err) {
    if (err?.status === 404) {
      throw new ServiceError(404, `Repository "${fullName}" was not found.`, 'NOT_FOUND');
    }
    if (err?.status === 403) {
      throw new ServiceError(403, `Access denied reading metadata for "${fullName}".`, 'INSUFFICIENT_PERMISSIONS');
    }
    throw new ServiceError(502, `Failed to load repository details: ${err.message}`, 'GITHUB_API_ERROR');
  }

  if (repoData.private) {
    await authorizeRepositoryRead({
      authorization,
      sessionToken,
      repoInput: fullName,
      githubContext,
      createUserClient
    });
  }

  const defaultBranch = repoData.default_branch || 'main';
  const conflicts = [];
  const warnings = [];

  if (repoData.archived) {
    warnings.push(`Repository "${fullName}" is archived and read-only. Pull requests cannot be merged.`);
  }

  // Inspect existing license
  let existingLicenses = [];
  try {
    existingLicenses = await detectExistingLicenseOnBranch(octokit, { owner, repo, defaultBranch });
  } catch (err) {
    warnings.push(`Could not inspect repository license files: ${err.message}`);
  }

  const existingLicensePath = existingLicenses[0] || null;
  let existingLicenseSha = null;
  if (existingLicensePath) {
    try {
      const fileRes = await octokit.rest.repos.getContent({ owner, repo, path: existingLicensePath, ref: defaultBranch });
      existingLicenseSha = fileRes.data?.sha || null;
    } catch {
      // Ignore content read error in preview
    }
  }

  if (existingLicenses.length > 1) {
    warnings.push(`Multiple license files found (${existingLicenses.join(', ')}). Manual review is required.`);
  }

  if (existingLicensePath && !replaceExisting) {
    conflicts.push({
      type: 'license_exists',
      detail: `Repository already contains "${existingLicensePath}". Select "Replace existing license" to update it.`
    });
  }

  if (replaceExisting && !existingLicensePath) {
    conflicts.push({
      type: 'license_not_found',
      detail: 'No existing license file found to replace. Select "Add new license" instead.'
    });
  }

  // Inspect README
  let readmeData = { exists: false, path: 'README.md', sha: null, content: '' };
  try {
    readmeData = await fetchRepositoryReadme(octokit, { owner, repo, ref: defaultBranch });
  } catch (err) {
    if (err.code === 'UNSUPPORTED_README') {
      warnings.push('README file is not a supported Markdown file.');
    } else {
      warnings.push(`Could not read README: ${err.message}`);
    }
  }

  const readmeInspection = inspectReadme(readmeData.content, validated.licenseId);
  for (const c of readmeInspection.conflicts) conflicts.push(c);
  for (const w of readmeInspection.warnings) warnings.push(w);

  const link = path.posix.relative(path.posix.dirname(readmeData.path), existingLicensePath || licensePackage.filename);
  let proposedReadme;
  let readmeChanged = false;

  if (typeof customReadmeContent === 'string') {
    proposedReadme = customReadmeContent;
    readmeChanged = proposedReadme !== readmeData.content;
  } else if (readmePlacement === 'none' && !badgeAction && !sectionAction) {
    proposedReadme = readmeData.content;
    readmeChanged = false;
  } else {
    proposedReadme = smartUpdateReadme(readmeData.content, {
      license: { id: validated.licenseId, name: licensePackage.name },
      licenseLink: link,
      badgeAction,
      sectionAction,
      placement: readmePlacement
    });
    readmeChanged = proposedReadme !== readmeData.content;
  }

  const readmeDiff = generateUnifiedDiff(readmeData.content, proposedReadme, readmeData.path);
  const targetBranch = formatLicenseBranchName(validated.licenseId, replaceExisting);
  const title = `chore: ${replaceExisting ? 'replace' : 'add'} ${validated.licenseId} LICENSE`;

  const files = [
    {
      path: existingLicensePath || licensePackage.filename,
      action: replaceExisting ? 'replace' : 'add',
      sha: existingLicenseSha
    }
  ];

  if (readmeChanged) {
    files.push({
      path: readmeData.path,
      action: readmeData.exists ? 'update' : 'create',
      sha: readmeData.sha
    });
  }

  const body = buildPullRequestBody({
    explanation,
    licensePackage,
    defaultBranch,
    existingLicensePath,
    readmeUpdate: readmeChanged
      ? { changed: true, path: readmeData.path, reviewExisting: readmeInspection.conflicts.length > 0 }
      : null,
    readmePlacement
  });

  return {
    ok: true,
    repository: fullName,
    defaultBranch,
    isArchived: Boolean(repoData.archived),
    appInstalled: installed,
    branch: targetBranch,
    title,
    body,
    files,
    license: {
      id: validated.licenseId,
      name: licensePackage.name,
      action: replaceExisting ? 'replace' : 'add',
      path: existingLicensePath || licensePackage.filename,
      sha: existingLicenseSha,
      content: licensePackage.content
    },
    readme: {
      exists: readmeData.exists,
      path: readmeData.path,
      sha: readmeData.sha,
      originalContent: readmeData.content,
      proposedContent: proposedReadme,
      changed: readmeChanged,
      diff: readmeDiff,
      inspection: readmeInspection
    },
    conflicts,
    warnings
  };
}

/**
 * Create a feature branch, commit the customized LICENSE file and verified README, and open a Pull Request.
 *
 * @param {object} params
 * @returns {Promise<object>}
 */
export async function createLicensePullRequest({
  repo: repoInput,
  licenseId,
  year,
  holder,
  replaceExisting = false,
  readmePlacement = 'none',
  badgeAction,
  sectionAction,
  customReadmeContent,
  expectedReadmeSha,
  expectedReadmeContent,
  expectedLicenseSha,
  confirmed,
  githubContext
}) {
  if (!README_PLACEMENTS.includes(readmePlacement)) {
    throw new ServiceError(400, 'readmePlacement must be none, top, bottom, or both.', 'INVALID_INPUT');
  }
  if (typeof replaceExisting !== 'boolean') {
    throw new ServiceError(400, 'replaceExisting must be a boolean.', 'INVALID_INPUT');
  }

  const isReadmeWorkflow = Boolean(
    badgeAction ||
    sectionAction ||
    customReadmeContent !== undefined ||
    expectedReadmeSha !== undefined ||
    expectedReadmeContent !== undefined
  );

  if (confirmed === false || (isReadmeWorkflow && confirmed !== true)) {
    throw new ServiceError(
      400,
      'Explicit review and confirmation of proposed README and LICENSE changes is required before creating a pull request.',
      'CONFIRMATION_REQUIRED'
    );
  }
  const validated = validatePrRequest({ repo: repoInput, licenseId, year, holder });
  const { owner, repo, fullName, explanation, licensePackage } = validated;

  if (!githubContext?.isAppConfigured || typeof githubContext.resolveRepoInstallation !== 'function') {
    throw new ServiceError(
      503,
      'GitHub App credentials are not configured on the server. Set GITHUB_APP_ID and private key credentials in .env.',
      'APP_NOT_CONFIGURED'
    );
  }

  let resolution;
  try {
    resolution = await githubContext.resolveRepoInstallation(owner, repo);
  } catch (err) {
    if (err?.status === 401 || err?.status === 403) {
      throw new ServiceError(403, 'GitHub App lacks permission to verify repository installation.', 'INSUFFICIENT_PERMISSIONS');
    }
    throw new ServiceError(502, `Unable to check GitHub App installation: ${err.message}`, 'GITHUB_API_ERROR');
  }

  if (!resolution?.installed || !resolution.octokit) {
    throw new ServiceError(
      404,
      `Open Workers is not installed on "${fullName}". Install the GitHub App on this repository first.`,
      'APP_NOT_INSTALLED'
    );
  }

  const perms = resolution.installation?.permissions || {};
  if (
    (perms.contents && perms.contents !== 'write') ||
    (perms.pull_requests && perms.pull_requests !== 'write')
  ) {
    throw new ServiceError(
      403,
      'GitHub App installation requires Contents (Read & write) and Pull Requests (Read & write) permissions.',
      'INSUFFICIENT_PERMISSIONS'
    );
  }

  const octokit = resolution.octokit;

  let repoData;
  try {
    repoData = await repositoryService(octokit, { owner, repo }).metadata();
  } catch (err) {
    if (err?.status === 403) {
      throw new ServiceError(403, `GitHub App lacks permission to read metadata for "${fullName}".`, 'INSUFFICIENT_PERMISSIONS');
    }
    if (err?.status === 404) {
      throw new ServiceError(404, `Repository "${fullName}" was not found.`, 'NOT_FOUND');
    }
    throw new ServiceError(502, `Failed to load repository details: ${err.message}`, 'GITHUB_API_ERROR');
  }

  if (repoData.archived) {
    throw new ServiceError(409, `Repository "${fullName}" is archived and read-only.`, 'REPO_ARCHIVED');
  }

  const defaultBranch = repoData.default_branch || 'main';

  // Resolve base commit SHA of default branch
  let baseSha;
  try {
    const refRes = await octokit.rest.git.getRef({ owner, repo, ref: `heads/${defaultBranch}` });
    baseSha = refRes.data.object.sha;
  } catch (err) {
    if (err?.status === 404 || err?.status === 409) {
      throw new ServiceError(
        409,
        `Default branch "${defaultBranch}" has no initial commits yet. Create an initial commit before opening a license PR.`,
        'EMPTY_REPOSITORY'
      );
    }
    if (err?.status === 403) {
      throw new ServiceError(403, 'GitHub App lacks permission to read Git references.', 'INSUFFICIENT_PERMISSIONS');
    }
    throw new ServiceError(502, `Failed to resolve default branch SHA: ${err.message}`, 'GITHUB_API_ERROR');
  }

  // Replacements require explicit opt-in and an unambiguous existing license.
  let existingLicensePath;
  try {
    const paths = await detectExistingLicenseOnBranch(octokit, { owner, repo, defaultBranch: baseSha });
    if (replaceExisting && paths.length > 1) {
      throw new ServiceError(409, 'Multiple license files found. Resolve which license to replace manually.', 'MULTIPLE_LICENSE_FILES');
    }
    existingLicensePath = paths[0] || null;
  } catch (err) {
    if (err instanceof ServiceError) throw err;
    if (err?.status === 403) {
      throw new ServiceError(403, `GitHub App lacks permission to inspect repository contents for "${fullName}".`, 'INSUFFICIENT_PERMISSIONS');
    }
    throw new ServiceError(502, `Failed to inspect existing repository license files: ${err.message}`, 'GITHUB_API_ERROR');
  }

  if (existingLicensePath && !replaceExisting) {
    throw new ServiceError(
      409,
      `Repository "${fullName}" already contains "${existingLicensePath}" on "${defaultBranch}". Choose "Replace existing license" to propose a replacement PR.`,
      'LICENSE_EXISTS',
      { existingPath: existingLicensePath, defaultBranch }
    );
  }

  if (replaceExisting && !existingLicensePath) {
    throw new ServiceError(409, 'No existing license found. Choose "Add new license" instead.', 'LICENSE_NOT_FOUND');
  }

  let existingFileSha;
  if (replaceExisting) {
    try {
      const { data } = await octokit.rest.repos.getContent({ owner, repo, path: existingLicensePath, ref: baseSha });
      if (data?.type !== 'file' || !data.sha) {
        throw new ServiceError(409, 'The existing license must be a regular file.', 'INVALID_LICENSE_FILE');
      }
      existingFileSha = data.sha;
    } catch (err) {
      if (err instanceof ServiceError) throw err;
      throw new ServiceError(502, `Failed to read existing license: ${err.message}`, 'GITHUB_API_ERROR');
    }

    if (expectedLicenseSha !== undefined && expectedLicenseSha !== null && existingFileSha !== expectedLicenseSha) {
      throw new ServiceError(
        409,
        `Repository LICENSE file has been modified since it was inspected (expected ${expectedLicenseSha}, found ${existingFileSha}). Refresh before proceeding.`,
        'LICENSE_STALE'
      );
    }
  }

  const action = replaceExisting ? 'replace' : 'add';
  const title = `chore: ${action} ${validated.licenseId} LICENSE`;

  const readmeUpdate = await prepareReadmeUpdate(octokit, {
    owner,
    repo,
    ref: baseSha,
    license: { id: validated.licenseId, name: licensePackage.name },
    licensePath: existingLicensePath || licensePackage.filename,
    placement: readmePlacement,
    badgeAction,
    sectionAction,
    customReadmeContent,
    expectedSha: expectedReadmeSha
  });

  if (expectedReadmeContent !== undefined && expectedReadmeContent !== null) {
    const actualProposed = readmeUpdate?.content ?? '';
    if (actualProposed !== expectedReadmeContent) {
      throw new ServiceError(
        409,
        'Proposed README content does not match the reviewed and confirmed preview. Re-review before proceeding.',
        'PREVIEW_CONTENT_MISMATCH',
        {
          expectedContent: expectedReadmeContent,
          actualContent: actualProposed
        }
      );
    }
  }

  const targetBranch = await createFeatureBranch(octokit, {
    owner,
    repo,
    defaultBranch,
    baseSha,
    baseBranchName: formatLicenseBranchName(validated.licenseId, replaceExisting)
  });

  // Commit generated LICENSE onto the dedicated feature branch
  let commitSha = null;
  try {
    commitSha = await commitFiles(octokit, {
      owner,
      repo,
      branch: targetBranch,
      defaultBranch,
      files: [{
        path: existingLicensePath || licensePackage.filename,
        sha: existingFileSha,
        message: title,
        content: licensePackage.content
      }]
    });
  } catch (err) {
    if (err?.status === 403 || err?.status === 404) {
      throw new ServiceError(
        403,
        'GitHub App lacks Contents write permission to commit the LICENSE file.',
        'INSUFFICIENT_PERMISSIONS'
      );
    }
    throw new ServiceError(502, `Failed to commit LICENSE file: ${err.message}`, 'GITHUB_API_ERROR');
  }

  if (readmeUpdate?.changed) {
    try {
      commitSha =
        (await commitFiles(octokit, {
          owner,
          repo,
          branch: targetBranch,
          defaultBranch,
          files: [{
            path: readmeUpdate.path,
            sha: readmeUpdate.sha,
            message: `docs: mention ${validated.licenseId} in README`,
            content: readmeUpdate.content
          }]
        })) || commitSha;
    } catch (err) {
      throw new ServiceError(
        502,
        `License was committed on feature branch "${targetBranch}", but README update failed; no PR was opened. ${err.message}`,
        'README_WRITE_FAILED'
      );
    }
  }

  // Open Pull Request only after file updates succeed
  const body = buildPullRequestBody({
    explanation,
    licensePackage,
    defaultBranch,
    existingLicensePath,
    readmeUpdate,
    readmePlacement
  });

  try {
    const prRes = await octokit.rest.pulls.create({
      owner,
      repo,
      title,
      head: targetBranch,
      base: defaultBranch,
      body
    });

    return {
      ok: true,
      repository: fullName,
      licenseId: validated.licenseId,
      branch: targetBranch,
      baseBranch: defaultBranch,
      commitSha,
      pullNumber: prRes.data.number,
      pullUrl: prRes.data.html_url,
      title: prRes.data.title
    };
  } catch (err) {
    if (err?.status === 403 || err?.status === 404) {
      throw new ServiceError(
        403,
        'GitHub App lacks Pull Requests write permission to open the pull request.',
        'INSUFFICIENT_PERMISSIONS'
      );
    }
    if (err?.status === 422) {
      throw new ServiceError(422, `GitHub rejected pull request creation: ${err.message}`, 'PR_VALIDATION_ERROR');
    }
    throw new ServiceError(502, `Failed to open pull request: ${err.message}`, 'GITHUB_API_ERROR');
  }
}
